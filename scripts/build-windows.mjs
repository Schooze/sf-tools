import {spawnSync} from 'node:child_process';
import {copyFile,mkdir,readdir,writeFile,readFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import path from 'node:path';
import './prepare-runtime.mjs';
const root=path.resolve(import.meta.dirname,'..');
const run=(cmd,args)=>{const r=spawnSync(cmd,args,{cwd:root,stdio:'inherit',shell:false});if(r.error)throw r.error;if(r.status!==0)process.exit(r.status??1);};
run(process.execPath,['node_modules/@tauri-apps/cli/tauri.js','build','--','--offline']);
const release=path.join(root,'release');await mkdir(release,{recursive:true});
await copyFile(path.join(root,'src-tauri/target/release/sf-tools.exe'),path.join(release,'sf-tools.exe'));
await copyFile(path.join(root,'src-tauri/WebView2Loader.dll'),path.join(release,'WebView2Loader.dll'));
const installers=await readdir(path.join(root,'src-tauri/target/release/bundle/nsis'));
const installer=installers.find(f=>f.endsWith('.exe')&&f.includes('0.2.0'));
if(!installer)throw Error('NSIS 0.2.0 installer missing');
await copyFile(path.join(root,'src-tauri/target/release/bundle/nsis',installer),path.join(release,'SF-Tools-Setup.exe'));
const lines=[];
for(const name of ['sf-tools.exe','WebView2Loader.dll','SF-Tools-Setup.exe'])lines.push(createHash('sha256').update(await readFile(path.join(release,name))).digest('hex')+'  '+name);
await writeFile(path.join(release,'SHA256SUMS.txt'),lines.join('\n')+'\n');
console.log('Published portable executable, matching loader and NSIS installer in release/');
